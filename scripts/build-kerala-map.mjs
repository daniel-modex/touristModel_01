#!/usr/bin/env node
/**
 * Builds src/app/data/kerala-map.ts: the 14 Kerala district shapes plus destination pins,
 * projected into one SVG coordinate space.
 *
 *   node scripts/build-kerala-map.mjs
 *
 * Source: data-src/kerala-districts.geojson, district boundaries from
 * https://github.com/udit-001/india-maps-data (Census of India 2011 district boundaries, no
 * explicit licence in the repository: see CREDITS.md).
 * Projection: equirectangular, longitude scaled by cos(mid-latitude) so the shape is not stretched.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const geo = JSON.parse(readFileSync(join(root, 'data-src/kerala-districts.geojson'), 'utf8'));

/** Real coordinates (WGS84) of the featured destinations. */
const PLACES = [
  { id: 'kannur', name: 'Kannur', note: 'Theyyam country', district: 'Kannur', lat: 11.8745, lon: 75.3704, season: 'Nov – Mar', image: 'images/cat-theyyam.jpg' },
  { id: 'wayanad', name: 'Wayanad', note: 'Forests & peaks', district: 'Wayanad', lat: 11.6103, lon: 76.083, season: 'Sep – May', image: 'images/cat-chembra.jpg' },
  { id: 'athirappilly', name: 'Athirappilly', note: 'Waterfalls', district: 'Thrissur', lat: 10.285, lon: 76.57, season: 'Jul – Dec', image: 'images/cat-athirappilly.jpg' },
  { id: 'kochi', name: 'Kochi', note: 'Heritage coast', district: 'Ernakulam', lat: 9.9312, lon: 76.2673, season: 'Oct – Mar', image: 'images/kochi.jpg' },
  { id: 'munnar', name: 'Munnar', note: 'Tea hills', district: 'Idukki', lat: 10.0889, lon: 77.0595, season: 'Sep – Mar', image: 'images/munnar.jpg' },
  { id: 'thekkady', name: 'Thekkady', note: 'Periyar wildlife', district: 'Idukki', lat: 9.6026, lon: 77.165, season: 'Oct – Mar', image: 'images/cat-periyar-lake.jpg' },
  { id: 'alleppey', name: 'Alleppey', note: 'Backwaters', district: 'Alappuzha', lat: 9.4981, lon: 76.3388, season: 'Nov – Feb', image: 'images/pkg-backwaters.jpg' },
  { id: 'varkala', name: 'Varkala', note: 'Cliff beach', district: 'Thiruvananthapuram', lat: 8.7379, lon: 76.7163, season: 'Nov – Mar', image: 'images/varkala.jpg' },
  { id: 'kovalam', name: 'Kovalam', note: 'Lighthouse beach', district: 'Thiruvananthapuram', lat: 8.4004, lon: 76.9787, season: 'Nov – Mar', image: 'images/kovalam.jpg' },
];

const polys = (f) => (f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [f.geometry.coordinates]);
let [x0, y0, x1, y1] = [Infinity, Infinity, -Infinity, -Infinity];
for (const f of geo.features)
  for (const p of polys(f))
    for (const r of p)
      for (const [x, y] of r) {
        x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y);
      }

const k = Math.cos((((y0 + y1) / 2) * Math.PI) / 180);
const H = 1000;
const scale = H / (y1 - y0);
const W = Math.round((x1 - x0) * k * scale);
const PAD = 40;
const px = (lon) => +((lon - x0) * k * scale + PAD).toFixed(1);
const py = (lat) => +((y1 - lat) * scale + PAD).toFixed(1);

const districts = geo.features.map((f) => ({
  name: f.properties.district,
  d:
    polys(f)
      .map((p) =>
        p
          .map((ring) => 'M' + ring.map(([lon, lat]) => `${px(lon)} ${py(lat)}`).join('L') + 'Z')
          .join(''),
      )
      .join(''),
}));

const pins = PLACES.map((p) => ({ ...p, x: px(p.lon), y: py(p.lat) }));

const ts = `// GENERATED by scripts/build-kerala-map.mjs. Do not edit by hand.
// District boundaries: github.com/udit-001/india-maps-data (Census of India 2011). See CREDITS.md.
export const KERALA_VIEWBOX = '0 0 ${W + PAD * 2} ${H + PAD * 2}';

export interface KeralaDistrict {
  name: string;
  d: string;
}

export interface KeralaPin {
  id: string;
  name: string;
  note: string;
  district: string;
  lat: number;
  lon: number;
  /** best time to visit */
  season: string;
  image: string;
  /** position in KERALA_VIEWBOX */
  x: number;
  y: number;
}

export const KERALA_DISTRICTS: KeralaDistrict[] = ${JSON.stringify(districts)};

export const KERALA_PINS: KeralaPin[] = ${JSON.stringify(pins, null, 2)};
`;
writeFileSync(join(root, 'src/app/data/kerala-map.ts'), ts);
console.log(`kerala-map.ts: ${districts.length} districts, ${pins.length} pins, viewBox ${W + PAD * 2}x${H + PAD * 2}, ${(ts.length / 1024).toFixed(1)} KB`);
